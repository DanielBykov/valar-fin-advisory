/**
 * Regenerates the reference file check-affordability.mjs compares against.
 *
 *   _original-calc.mjs  the calculator lifted verbatim out of the standalone
 *                       HTML it was first written in, with a tiny shim standing
 *                       in for the DOM it reads its inputs from.
 *
 * The ported side needs no build step — node reads src/lib/affordability.ts
 * directly. Generated, and gitignored. Run this, then the check:
 *
 *   node scripts/build-affordability-check.mjs && node scripts/check-affordability.mjs
 *
 * or just `npm run check:affordability`, which does both.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..");

// The original lives outside the repo, in the workspace it was drafted in.
const ORIGINAL_HTML = resolve(repo, "../calculators/fhb-affordability.html");

const html = readFileSync(ORIGINAL_HTML, "utf8");
const script = html.split("<script>")[1]?.split("</script>")[0];
if (!script) throw new Error(`No <script> block found in ${ORIGINAL_HTML}`);

/*
 * The original reads every input through document.getElementById(id).value and
 * writes its answers back into .textContent / .innerHTML. The shim gives it
 * objects that read from one plain record and write into another, so the
 * arithmetic underneath runs exactly as written.
 */
const shim = `// GENERATED by scripts/build-affordability-check.mjs — do not edit.
let __in = {};
let __out = {};
const document = {
  getElementById: (id) => ({
    get value() { return String(__in[id] ?? ""); },
    set value(v) { __in[id] = v; },
    classList: { add() {}, remove() {}, toggle() {} },
    addEventListener() {}, removeEventListener() {}, setAttribute() {},
    style: {}, hidden: false, offsetWidth: 0,
    set textContent(v) { __out[id] = v; },
    get textContent() { return __out[id]; },
    set innerHTML(v) { __out[id] = v; },
    get innerHTML() { return __out[id]; },
  }),
  querySelectorAll: () => [],
};
`;

const body = script
  .trim()
  .replace('(function () {\n  "use strict";', "")
  .replace(/\}\)\(\);\s*$/, "");

const exposed = `
export function runOriginal(inputs, detailedMode) {
  __in = inputs;
  __out = {};
  detailed = detailedMode;
  calc();
  return { ...__out };
}
`;

writeFileSync(resolve(here, "_original-calc.mjs"), shim + body + exposed, "utf8");

console.log("Regenerated _original-calc.mjs");
